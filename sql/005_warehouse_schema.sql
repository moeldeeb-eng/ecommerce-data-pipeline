CREATE SCHEMA IF NOT EXISTS warehouse;

CREATE TABLE IF NOT EXISTS warehouse.build_runs (
 run_id text PRIMARY KEY REFERENCES store.ingestion_runs(run_id),
 source_manifest_sha256 char(64) NOT NULL,
 model_version text NOT NULL,
 checked_at_utc timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS warehouse.dim_date (
 date_key integer PRIMARY KEY,
 full_date date NOT NULL UNIQUE,
 calendar_year smallint NOT NULL,
 calendar_quarter smallint NOT NULL CHECK (calendar_quarter BETWEEN 1 AND 4),
 month_number smallint NOT NULL CHECK (month_number BETWEEN 1 AND 12),
 month_name text NOT NULL,
 day_of_month smallint NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
 iso_day_of_week smallint NOT NULL CHECK (iso_day_of_week BETWEEN 1 AND 7),
 day_name text NOT NULL,
 iso_week smallint NOT NULL CHECK (iso_week BETWEEN 1 AND 53),
 iso_year smallint NOT NULL,
 CHECK (date_key=extract(year FROM full_date)::integer*10000+extract(month FROM full_date)::integer*100+extract(day FROM full_date)::integer)
);

CREATE TABLE IF NOT EXISTS warehouse.dim_product (
 product_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id text NOT NULL REFERENCES store.ingestion_runs(run_id),
 asin varchar(10) NOT NULL,
 product_name text NOT NULL,
 category text NOT NULL,
 observed_price numeric(14,2),
 observed_currency varchar(3),
 observed_rating numeric(2,1),
 observed_ratings_count bigint,
 simulation_anchor_price numeric(14,2) NOT NULL,
 simulation_anchor_method text NOT NULL,
 UNIQUE (run_id,asin),
 UNIQUE (run_id,product_key),
 FOREIGN KEY (run_id,asin) REFERENCES store.products(run_id,asin)
);

CREATE TABLE IF NOT EXISTS warehouse.dim_customer (
 customer_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id text NOT NULL REFERENCES store.ingestion_runs(run_id),
 customer_id text NOT NULL,
 customer_name text NOT NULL,
 email text NOT NULL,
 city text NOT NULL,
 country char(2) NOT NULL,
 registered_at_utc timestamptz NOT NULL,
 is_synthetic boolean NOT NULL CHECK (is_synthetic),
 UNIQUE (run_id,customer_id),
 UNIQUE (run_id,customer_key),
 FOREIGN KEY (run_id,customer_id) REFERENCES store.customers(run_id,customer_id)
);

CREATE TABLE IF NOT EXISTS warehouse.fact_sales (
 run_id text NOT NULL,
 order_id text NOT NULL,
 line_number smallint NOT NULL,
 product_key bigint NOT NULL,
 customer_key bigint NOT NULL,
 date_key integer NOT NULL REFERENCES warehouse.dim_date(date_key),
 ordered_at_utc timestamptz NOT NULL,
 order_status text NOT NULL CHECK (order_status IN ('completed','cancelled','payment_failed')),
 payment_status text NOT NULL CHECK (payment_status IN ('paid','cancelled','failed')),
 quantity smallint NOT NULL CHECK (quantity BETWEEN 1 AND 4),
 realized_quantity smallint NOT NULL CHECK (realized_quantity >= 0),
 unit_price numeric(14,2) NOT NULL CHECK (unit_price > 0),
 discount_percent smallint NOT NULL CHECK (discount_percent IN (0,5,10,15)),
 gross_amount numeric(16,2) NOT NULL,
 discount_amount numeric(16,2) NOT NULL,
 net_amount numeric(16,2) NOT NULL,
 realized_net_amount numeric(16,2) NOT NULL CHECK (realized_net_amount >= 0),
 currency char(3) NOT NULL CHECK (currency='EGP'),
 price_method text NOT NULL,
 is_synthetic boolean NOT NULL CHECK (is_synthetic),
 PRIMARY KEY (run_id,order_id,line_number),
 FOREIGN KEY (run_id,order_id,line_number) REFERENCES store.order_items(run_id,order_id,line_number),
 FOREIGN KEY (run_id,product_key) REFERENCES warehouse.dim_product(run_id,product_key),
 FOREIGN KEY (run_id,customer_key) REFERENCES warehouse.dim_customer(run_id,customer_key),
 CHECK (gross_amount=unit_price*quantity),
 CHECK (discount_amount=round(gross_amount*discount_percent/100,2)),
 CHECK (net_amount=gross_amount-discount_amount),
 CHECK ((order_status='completed' AND payment_status='paid' AND realized_quantity=quantity AND realized_net_amount=net_amount)
     OR (order_status='cancelled' AND payment_status='cancelled' AND realized_quantity=0 AND realized_net_amount=0)
     OR (order_status='payment_failed' AND payment_status='failed' AND realized_quantity=0 AND realized_net_amount=0))
);

CREATE INDEX IF NOT EXISTS warehouse_sales_date_idx ON warehouse.fact_sales(run_id,date_key);
CREATE INDEX IF NOT EXISTS warehouse_sales_product_idx ON warehouse.fact_sales(run_id,product_key);
CREATE INDEX IF NOT EXISTS warehouse_sales_customer_idx ON warehouse.fact_sales(run_id,customer_key);

CREATE OR REPLACE VIEW warehouse.v_sales_detail AS
SELECT f.*,p.asin,p.product_name,p.category,c.customer_id,c.city,c.country,
       d.full_date,d.calendar_year,d.month_number,d.month_name
FROM warehouse.fact_sales f
JOIN warehouse.dim_product p ON p.run_id=f.run_id AND p.product_key=f.product_key
JOIN warehouse.dim_customer c ON c.run_id=f.run_id AND c.customer_key=f.customer_key
JOIN warehouse.dim_date d ON d.date_key=f.date_key;

CREATE OR REPLACE VIEW warehouse.v_monthly_category_sales AS
SELECT f.run_id,f.currency,d.calendar_year,d.month_number,p.category,
       count(*) AS attempted_order_lines,
       count(*) FILTER (WHERE f.order_status='completed') AS completed_order_lines,
       count(DISTINCT f.order_id) FILTER (WHERE f.order_status='completed') AS completed_orders_in_category,
       sum(f.realized_quantity) AS realized_units,
       sum(f.realized_net_amount) AS realized_item_revenue
FROM warehouse.fact_sales f
JOIN warehouse.dim_product p ON p.run_id=f.run_id AND p.product_key=f.product_key
JOIN warehouse.dim_date d ON d.date_key=f.date_key
GROUP BY f.run_id,f.currency,d.calendar_year,d.month_number,p.category;
